export type Page = "overview" | "procurement" | "inventory" | "production" | "sales" | "finance" | "workspace";
export type Entity = { id: string };
export type Company = { id: string; name: string; role: string; address?: string; phone?: string };
export type Session = { user: { id: string; name: string; email: string }; companies: Company[]; csrfToken: string };
export type Item = Entity & {
  sku: string;
  name: string;
  kind: "raw" | "finished";
  unit: string;
  reorderLevel: string;
  unitCost: string;
  sellingPrice: string;
};
export type Party = Entity & { code: string; name: string; email: string; phone: string; address: string };
export type Warehouse = Entity & { code: string; name: string };
export type Stock = {
  itemId: string;
  warehouseId: string;
  itemName: string;
  sku: string;
  kind: string;
  unit: string;
  warehouseName: string;
  onHand: string;
  reserved: string;
  available: string;
  unitCost: string;
  reorderLevel: string;
};
export type Line = {
  id: string;
  itemId: string;
  itemName: string;
  unit: string;
  quantity: string;
  receivedQuantity?: string;
  dispatchedQuantity?: string;
  unitPrice: string;
  plannedQuantity?: string;
  issuedQuantity?: string;
  returnedQuantity?: string;
  unitCost?: string;
};
export type Document = Entity & {
  code: string;
  supplierId?: string;
  supplierName?: string;
  customerId?: string;
  customerName?: string;
  warehouseId: string;
  warehouseName: string;
  status: string;
  total: string;
  createdAt: string;
  lines: Line[];
  orderDate?: string;
  expectedDate?: string | null;
  supplierReference?: string | null;
  paymentTerms?: string | null;
  deliveryAddress?: string | null;
  notes?: string | null;
};
export type Receipt = Document & { purchaseOrderId: string; purchaseOrderCode: string; billId: string | null };
export type Dispatch = Document & { salesOrderId: string; salesOrderCode: string; invoiceId: string | null };
export type Bill = Entity & {
  code: string;
  direction: "payable" | "receivable";
  partyId: string;
  partyName: string;
  sourceId: string;
  sourceCode: string;
  total: string;
  paid: string;
  balance: string;
  status: string;
  dueDate: string;
  createdAt: string;
};
export type Bom = Entity & {
  code: string;
  name: string;
  productId: string;
  productName: string;
  version: number;
  lines: Line[];
};
export type WorkOrder = Document & {
  bomId: string;
  productId: string;
  productName: string;
  plannedQuantity: string;
  goodQuantity: string;
  rejectedQuantity: string;
  labourCost: string;
  materialCost: string;
  unitCost: string;
};
export type Activity = Entity & {
  action: string;
  entityType: string;
  entityId: string;
  description: string;
  createdAt: string;
};
export type Payment = Entity & {
  code: string;
  billId: string;
  billCode: string;
  direction: Bill["direction"];
  partyName: string;
  amount: string;
  method: "bank" | "cash" | "upi";
  note: string | null;
  createdAt: string;
};
export type Expense = Entity & {
  code: string;
  category: string;
  description: string;
  amount: string;
  expenseDate: string;
  createdAt: string;
};
export type StockMovement = Entity & {
  itemId: string;
  itemName: string;
  warehouseId: string;
  warehouseName: string;
  quantity: string;
  unitCost: string;
  movement: string;
  referenceCode: string | null;
  note: string | null;
  createdAt: string;
};
// TODO(why): the legacy generic dialogs accept several record kinds; use a discriminated union
// when those forms are separated, rather than changing their dispatch behavior in Phase 0.
export type DialogRecord = Entity & Partial<Item & Party & Document & Bill & Bom & WorkOrder>;
export type Workspace = {
  company: Company;
  summary: {
    revenue: string;
    collected: string;
    receivables: string;
    payables: string;
    expenses: string;
    inventoryValue: string;
    openPurchases: number;
    activeWorkOrders: number;
    openSales: number;
    lowStockCount: number;
  };
  items: Item[];
  warehouses: Warehouse[];
  suppliers: Party[];
  customers: Party[];
  inventory: Stock[];
  stockLedger: StockMovement[];
  purchaseOrders: Document[];
  receipts: Receipt[];
  bills: Bill[];
  payments: Payment[];
  boms: Bom[];
  workOrders: WorkOrder[];
  salesOrders: Document[];
  dispatches: Dispatch[];
  expenses: Expense[];
  activity: Activity[];
};
